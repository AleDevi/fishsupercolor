"""Rewrite the generated part of LLM_PROMPT.md (between the AUTO markers) from the code, the README and the
CHANGELOG, so the facts an LLM needs (version, modules, screens, profiles, plans) never drift from the repository.

python tools/update_llm_prompt.py          rewrite LLM_PROMPT.md
python tools/update_llm_prompt.py --check  exit 1 if LLM_PROMPT.md is out of date (used by GitHub Actions)

Standard library only, and nothing from guppycolor is imported (no PySide6 or torch needed)."""
import argparse
import ast
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROMPT = os.path.join(ROOT, 'LLM_PROMPT.md')
START = '<!-- AUTO:START (generated by tools/update_llm_prompt.py: do not edit by hand) -->'
END = '<!-- AUTO:END -->'
RECENT = 5      # CHANGELOG versions listed


def read(*parts):
    with open(os.path.join(ROOT, *parts), encoding='utf-8') as f:
        return f.read()


def version():
    return re.search(r"__version__ = '([^']+)'", read('guppycolor', '__init__.py')).group(1)


def first_sentence(text, limit=160):
    """First sentence of a paragraph, cut at a word boundary when longer than limit."""
    text = ' '.join(text.split())
    m = re.search(r'\.(?=\s+[A-Z(`*]|$)|;\s', text)
    text = text[:m.start()] if m else text
    return text if len(text) <= limit else text[:limit].rsplit(' ', 1)[0] + '…'


def modules():
    rows = []
    for folder, dirs, files in os.walk(os.path.join(ROOT, 'guppycolor')):
        dirs[:] = sorted(d for d in dirs if d != '__pycache__')
        for name in sorted(files):
            if not name.endswith('.py'):
                continue
            path = os.path.join(folder, name)
            with open(path, encoding='utf-8') as f:
                doc = ast.get_docstring(ast.parse(f.read()))
            if doc:
                rows.append((os.path.relpath(path, ROOT).replace(os.sep, '/'), first_sentence(doc.strip().split('\n\n')[0])))
    return rows


def tests():
    rows = []
    for name in sorted(os.listdir(os.path.join(ROOT, 'tests'))):
        if name.startswith('test_') and name.endswith('.py'):
            n = len(re.findall(r'^def test_', read('tests', name), re.M))
            rows.append((name, n))
    return rows


def sections(text, level):
    """{heading: body} for the headings of one level ('## ' or '### ')."""
    out, key = {}, None
    for line in text.splitlines():
        if line.startswith('#') and line.split(' ', 1)[0] == level.strip():
            key = line[len(level):].strip()
            out[key] = []
        elif line.startswith('#') and len(line.split(' ', 1)[0]) < len(level.strip()):
            key = None
        elif key is not None:
            out[key].append(line)
    return {k: '\n'.join(v).strip() for k, v in out.items()}


def screens():
    workflow = sections(read('README.md'), '## ').get('Workflow', '')
    return [h for h in sections(workflow, '### ') if re.match(r'\d+ ', h)]


def changelog():
    s = sections(read('CHANGELOG.md'), '## ')
    planned = [l for l in s.pop('Planned', '').splitlines() if l.strip()]
    recent = []
    for heading, body in list(s.items())[:RECENT]:
        bullets = [re.sub(r'\*\*', '', l[2:]).strip() for l in body.splitlines() if l.startswith('- ')]
        summary = '; '.join(first_sentence(b, 90) for b in bullets)
        recent.append(f'- **{heading}**: {summary}' + ('' if summary.endswith('…') else '.'))
    return planned, recent


def profiles():
    out = []
    folder = os.path.join(ROOT, 'guppycolor', 'profiles')
    for name in sorted(os.listdir(folder)):
        if name.endswith('.json'):
            with open(os.path.join(folder, name), encoding='utf-8') as f:
                p = json.load(f)
            lm = ', '.join(l['key'] + ('' if l.get('required') else ' (optional)') for l in p.get('landmarks', []))
            out += [f'- `{name}` ({p.get("name", "")})',
                    f'  - parts: {", ".join(x["key"] for x in p.get("parts", []))}',
                    f'  - colour classes: {", ".join(x["key"] for x in p.get("colour_classes", []))}',
                    f'  - landmarks, in clicking order: {lm}']
    return out


def toolchain():
    py = re.search(r'python-version:\s*"([^"]+)"', read('.github', 'workflows', 'tests.yml')).group(1)
    pins = re.findall(r'^([A-Za-z0-9_.-]+==[^\s#]+)', read('requirements.in'), re.M)
    return py, pins


def generated():
    planned, recent = changelog()
    py, pins = toolchain()
    lines = [START, '', '### Current state (generated)', '',
             f'- Version: **{version()}** (`guppycolor/__init__.py` and `pyproject.toml`).',
             f'- Target Python: **{py}** on Windows (tests and installer). Pinned in `requirements.in`: '
             + (', '.join(f'`{p}`' for p in pins) or 'none') + '.',
             '- App screens (README, Workflow): ' + '; '.join(screens()) + '.',
             '', '#### Recent versions (CHANGELOG)', '', *recent,
             '', '#### Planned (CHANGELOG)', '', *planned,
             '', '#### Species profiles', '', *profiles(),
             '', '#### Modules (first line of each docstring)', '', '| File | What it does |', '| --- | --- |',
             *[f'| `{p}` | {d.replace("|", "/")} |' for p, d in modules()],
             '', '#### Tests', '',
             '- ' + ', '.join(f'`{n}` ({k})' for n, k in tests()) + '.',
             '', END]
    return '\n'.join(lines)


def updated(text):
    i, j = text.find(START), text.find(END)
    if i < 0 or j < i:
        sys.exit(f'{PROMPT}: AUTO markers not found')
    return text[:i] + generated() + text[j + len(END):]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--check', action='store_true', help='only check, exit 1 if out of date')
    args = ap.parse_args()
    with open(PROMPT, encoding='utf-8') as f:
        text = f.read()
    new = updated(text)
    if args.check:
        if new != text:
            print('LLM_PROMPT.md is out of date: run  python tools/update_llm_prompt.py  and commit the result.')
            sys.exit(1)
        print('LLM_PROMPT.md is up to date.')
        return
    if new != text:
        with open(PROMPT, 'w', encoding='utf-8', newline='\n') as f:
            f.write(new)
        print('LLM_PROMPT.md updated.')
    else:
        print('LLM_PROMPT.md already up to date.')


if __name__ == '__main__':
    main()
